import { chromium } from '@playwright/test';
import { writeFileSync } from 'node:fs';
const browser=await chromium.launch({headless:true,executablePath:process.env.TZCG_CHROMIUM});
const page=await browser.newPage({viewport:{width:1100,height:850},timezoneId:'Asia/Tokyo'});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto(process.env.TZCG_DEMO_URL||'http://127.0.0.1:5174/');
const ids=()=>page.locator('[data-tzcg-row]').evaluateAll(rows=>rows.map(r=>r.dataset.tzcgRow));
await page.locator('[data-tzcg-row="__local"]').waitFor();
const before=await ids();
const height=await page.locator('section.tzcg').evaluate(e=>e.getBoundingClientRect().height);
await page.getByRole('combobox').fill('GRU');
await page.getByRole('listbox').waitFor();
const after=await page.locator('section.tzcg').evaluate(e=>e.getBoundingClientRect().height);
if(height!==after)throw Error('Search changes widget height');
await page.screenshot({path:'outputs/search-floating.png',fullPage:true});
await page.getByRole('option').first().click();
const local=await page.locator('[data-tzcg-row="__local"] .tzcg-drag').boundingBox();
const target=await page.locator('[data-tzcg-row]').nth(2).boundingBox();
await page.mouse.move(local.x+local.width/2,local.y+local.height/2);
await page.mouse.down();
await page.mouse.move(target.x+40,target.y+target.height/2,{steps:12});
await page.mouse.up();
const reordered=await ids();
if(reordered[2]!=='__local')throw Error('Mouse reorder failed');
if(await page.locator('[data-tzcg-row="__local"] .tzcg-remove').count())throw Error('Local removable');
await page.getByRole('button',{name:'Excluir São Paulo GRU'}).click();
await page.getByRole('tab',{name:/Grid/}).click();
if(JSON.stringify(await ids())!==JSON.stringify(reordered.filter(id=>!id.startsWith('airport-'))))throw Error('Grid order mismatch');
await page.screenshot({path:'outputs/grid-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'outputs/grid-mobile.png',fullPage:true});
if(!(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)))throw Error('Mobile overflow');
await page.getByRole('tab',{name:/Lista/}).click();
await page.screenshot({path:'outputs/list-mobile.png',fullPage:true});
// Touch path uses the same pointer handlers, tested with real Chromium touch events.
const mobile=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,timezoneId:'Asia/Tokyo'});
await mobile.goto(process.env.TZCG_DEMO_URL||'http://127.0.0.1:5174/');
await mobile.locator('[data-tzcg-row="__local"]').waitFor();
await mobile.getByRole('combobox').fill('KTM');
await mobile.getByRole('option').first().tap();
await mobile.getByText('KTM',{exact:true}).waitFor();
const source=await mobile.locator('[data-tzcg-row="__local"] .tzcg-drag').boundingBox();
const destination=await mobile.locator('[data-tzcg-row]').nth(1).boundingBox();
const cdp=await mobile.context().newCDPSession(mobile);
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:source.x+source.width/2,y:source.y+source.height/2}]});
await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:destination.x+40,y:destination.y+destination.height/2}]});
await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
const mobileOrder=await mobile.locator('[data-tzcg-row]').evaluateAll(rows=>rows.map(r=>r.dataset.tzcgRow));
if(mobileOrder[1]!=='__local')throw Error('Touch reorder failed');
if(errors.length)throw Error(errors.join('\n'));
writeFileSync('outputs/VALIDACAO-INTERACOES.json',JSON.stringify({floatingHeightUnchanged:true,mouseReorder:true,touchReorder:true,touchSearch:true,localProtected:true,gridOrderPreserved:true,pageErrors:errors},null,2));
console.log('Floating search, mouse/touch reorder, delete, local protection and shared grid order: OK');
await browser.close();
